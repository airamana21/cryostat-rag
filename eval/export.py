# ─── Accessors ────────────────────────────────────────────────────────────────

def _variant(scores: Dict, name: str) -> Dict:
    return scores.get("variants", {}).get(name, {})


def _retr(scores: Dict, name: str, key: str) -> Optional[Dict]:
    """Retrieval CI dict {mean, ci_low, ci_high} for a variant/metric."""
    return (_variant(scores, name).get("retrieval", {})
            .get("overall", {}).get(key))


def _vertex(scores: Dict, name: str, metric: str) -> Optional[Dict]:
    """Vertex CI dict {mean, ci_low, ci_high} for a variant/metric."""
    return _variant(scores, name).get("vertex_eval", {}).get("ci", {}).get(metric)


def _gen_extra(scores: Dict, name: str, key: str) -> Optional[Dict]:
    """ROUGE-L / citation-accuracy CI dict for a variant."""
    return (_variant(scores, name).get("generation_extra", {})
            .get("overall", {}).get(key))


def _mean(ci: Optional[Dict]) -> Optional[float]:
    return ci.get("mean") if isinstance(ci, dict) else None


# ─── Formatting ───────────────────────────────────────────────────────────────

def _f(val: Optional[float], digits: int = 3) -> str:
    return "---" if val is None else f"{val:.{digits}f}"


def _f_ci(ci: Optional[Dict], digits: int = 3) -> str:
    m = _mean(ci)
    if m is None:
        return "---"
    lo, hi = ci.get("ci_low"), ci.get("ci_high")
    if lo is None or hi is None:
        return f"{m:.{digits}f}"
    return f"{m:.{digits}f} \\tiny[{lo:.{digits}f}, {hi:.{digits}f}]"


def _delta(var_ci, full_ci, digits: int = 3) -> str:
    a, b = _mean(var_ci), _mean(full_ci)
    if a is None or b is None:
        return "---"
    d = a - b
    return f"{d:+.{digits}f}"


def _sig(p: Optional[float]) -> str:
    if p is None:
        return ""
    if p < 0.01:
        return "$^{**}$"
    if p < 0.05:
        return "$^{*}$"
    return ""


_HEADER = "% Auto-generated by eval/export.py — do not edit by hand.\n"


# ─── Table 3: retrieval configurations ────────────────────────────────────────

_RETRIEVAL_ROWS = [
    ("dense_only", "Dense only"),
    ("bm25_only",  "BM25 only"),
    ("rrf_only",   "Dense $+$ BM25 (RRF)"),
    ("rrf_rerank", "$+$ semantic rerank"),
]


def _table_retrieval(scores: Dict) -> str:
    lines = [
        _HEADER,
        "\\begin{table}[t]\n\\centering\n",
        "\\caption{Retrieval metrics across the four hybrid-pipeline configurations "
        "(routing and context expansion disabled to isolate the retriever). "
        "Means over the labelled question bank; 95\\% bootstrap CIs in brackets.}\n",
        "\\label{tab:retrieval-results}\n",
        "\\begin{tabular}{lcccc}\n\\toprule\n",
        "\\textbf{Configuration} & \\textbf{Recall@1} & \\textbf{Recall@5} "
        "& \\textbf{MRR} & \\textbf{Precision@5} \\\\\n\\midrule\n",
    ]
    for name, disp in _RETRIEVAL_ROWS:
        r1  = _f_ci(_retr(scores, name, "recall@1"))
        r5  = _f_ci(_retr(scores, name, "recall@5"))
        mrr = _f_ci(_retr(scores, name, "mrr"))
        p5  = _f_ci(_retr(scores, name, "precision@5"))
        lines.append(f"{disp} & {r1} & {r5} & {mrr} & {p5} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    return "".join(lines)


# ─── Table 4: generation, full vs baselines ───────────────────────────────────

_GENERATION_ROWS = [
    ("vanilla_llm",  "Bare LLM (Gemini 2.5 Pro)"),
    ("long_context", "Long-context LLM"),
    ("naive_rag",    "Naive RAG"),
    ("full_system",  "Cryostat AI Support Bot (full)"),
]


def _table_generation(scores: Dict) -> str:
    lines = [
        _HEADER,
        "\\begin{table}[t]\n\\centering\n",
        "\\caption{End-to-end answer quality: full system vs.\\ baselines. "
        "Faithfulness and answer correctness are 1--5 Gemini-judged rubrics "
        "(Vertex AI Evaluation SDK); citation accuracy and ROUGE-L are computed "
        "against the authored gold answers. 95\\% bootstrap CIs in brackets.}\n",
        "\\label{tab:generation-results}\n",
        "\\begin{tabular}{lcccc}\n\\toprule\n",
        "\\textbf{System} & \\textbf{Faithfulness} & \\textbf{Answer corr.} "
        "& \\textbf{Citation acc.} & \\textbf{ROUGE-L} \\\\\n\\midrule\n",
    ]
    for name, disp in _GENERATION_ROWS:
        faith = _f_ci(_vertex(scores, name, "context_faithfulness"))
        corr = _f_ci(_vertex(scores, name, "answer_correctness"))
        cite = _f_ci(_gen_extra(scores, name, "citation_accuracy"))
        rouge = _f_ci(_gen_extra(scores, name, "rouge_l"))
        lines.append(f"{disp} & {faith} & {corr} & {cite} & {rouge} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    return "".join(lines)


# ─── Table 5: per-component ablations (deltas vs full system) ──────────────────

_ABLATION_ROWS = [
    ("no_dual_granularity",  "$-$ dual-granularity (single index)"),
    ("no_bm25",              "$-$ BM25 leg"),
    ("no_reranking",         "$-$ managed semantic rerank"),
    ("no_context_expansion", "$-$ context expansion"),
    ("no_domain_prompt",     "$-$ domain-specific prompt"),
]


def _table_ablation(scores: Dict) -> str:
    full = "full_system"
    lines = [
        _HEADER,
        "\\begin{table}[t]\n\\centering\n",
        "\\caption{Per-component ablation of the full system: change in each "
        "metric when exactly one component is removed (variant minus full system). "
        "Negative values indicate the component helps. Significance from paired "
        "Wilcoxon signed-rank tests vs.\\ the full system.}\n",
        "\\label{tab:ablation-results}\n",
        "\\begin{tabular}{lccc}\n\\toprule\n",
        "\\textbf{Ablation} & \\textbf{$\\Delta$ Recall@5} "
        "& \\textbf{$\\Delta$ Faithfulness} & \\textbf{$\\Delta$ Citation acc.} \\\\\n\\midrule\n",
    ]
    for name, disp in _ABLATION_ROWS:
        sig = _variant(scores, name).get("significance_vs_full", {})
        d_r5 = _delta(_retr(scores, name, "recall@5"), _retr(scores, full, "recall@5"))
        d_fa = _delta(_vertex(scores, name, "context_faithfulness"),
                      _vertex(scores, full, "context_faithfulness"))
        d_ci = _delta(_gen_extra(scores, name, "citation_accuracy"),
                      _gen_extra(scores, full, "citation_accuracy"))
        m_r5 = _sig(sig.get("recall@5", {}).get("p_value"))
        m_fa = _sig(sig.get("context_faithfulness", {}).get("p_value"))
        m_ci = _sig(sig.get("citation_accuracy", {}).get("p_value"))
        lines.append(f"{disp} & {d_r5}{m_r5} & {d_fa}{m_fa} & {d_ci}{m_ci} \\\\\n")
    lines.append(
        "\\bottomrule\n\\end{tabular}\n\n"
        "\\begin{minipage}{0.95\\linewidth}\\footnotesize\n"
        "$^{*}p<0.05$, $^{**}p<0.01$ vs.\\ full system (paired Wilcoxon "
        "signed-rank, aligned by question). Multi-modal image attachment and "
        "follow-up reformulation are evaluated qualitatively (\\S\\ref{sec:eval}).\n"
        "\\end{minipage}\n"
        "\\end{table}\n"
    )
    return "".join(lines)


# ─── Table 6: operational metrics ─────────────────────────────────────────────

def _ops_pair(stats: Optional[Dict], digits: int = 2):
    if not isinstance(stats, dict):
        return "---", "---"
    med = stats.get("median")
    p95 = stats.get("p95")
    return (_f(med, digits), _f(p95, digits))


def _table_ops(scores: Dict) -> str:
    ops = scores.get("ops", {})
    timing = ops.get("timing", {})
    cost = ops.get("cost_usd", {})
    clar = ops.get("clarification_rate")

    t_total = _ops_pair(timing.get("total"))
    t_retr = _ops_pair(timing.get("retrieval"))
    t_rerank = _ops_pair(timing.get("rerank"))
    t_gen = _ops_pair(timing.get("generation"))
    c_med, c_p95 = _ops_pair(cost, digits=4)
    clar_str = "---" if clar is None else f"{clar * 100:.1f}"

    lines = [
        _HEADER,
        "\\begin{table}[t]\n\\centering\n",
        "\\caption{Operational metrics for the full system in the evaluation "
        "environment. Latencies decomposed by pipeline stage (context expansion "
        "is included in retrieval). Cost per query from token counts at list "
        "prices; clarification rate is the fraction of queries routed to the "
        "vagueness branch.}\n",
        "\\label{tab:ops-results}\n",
        "\\begin{tabular}{lcc}\n\\toprule\n",
        "\\textbf{Metric} & \\textbf{Median} & \\textbf{p95} \\\\\n\\midrule\n",
        f"End-to-end latency (s)              & {t_total[0]} & {t_total[1]} \\\\\n",
        f"\\quad retrieval $+$ expansion (s)   & {t_retr[0]} & {t_retr[1]} \\\\\n",
        f"\\quad semantic rerank API (s)       & {t_rerank[0]} & {t_rerank[1]} \\\\\n",
        f"\\quad LLM generation (s)            & {t_gen[0]} & {t_gen[1]} \\\\\n",
        f"Cost per query (USD)                & {c_med} & {c_p95} \\\\\n",
        f"Clarification rate (\\%)             & {clar_str} & --- \\\\\n",
        "\\bottomrule\n\\end{tabular}\n\\end{table}\n",
    ]
    return "".join(lines)


# ─── Figure 5: two-panel evaluation summary ───────────────────────────────────

def _yerr(cis):
    """Build asymmetric yerr arrays from a list of CI dicts (or None)."""
    lo, hi = [], []
    for ci in cis:
        m = _mean(ci)
        if m is None:
            lo.append(0.0)
            hi.append(0.0)
        else:
            lo.append(max(0.0, m - (ci.get("ci_low") if ci.get("ci_low") is not None else m)))
            hi.append(max(0.0, (ci.get("ci_high") if ci.get("ci_high") is not None else m) - m))
    return [lo, hi]


def _figure_eval(scores: Dict, out_base: str):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        print("  [skip] matplotlib not installed")
        return

    fig, (ax_top, ax_bot) = plt.subplots(2, 1, figsize=(7, 8))

    # Top: Recall@5 across retrieval configurations.
    top_labels = [d for _, d in _RETRIEVAL_ROWS]
    top_cis = [_retr(scores, n, "recall@5") for n, _ in _RETRIEVAL_ROWS]
    top_vals = [(_mean(c) or 0.0) for c in top_cis]
    x = np.arange(len(top_labels))
    ax_top.bar(x, top_vals, 0.6, yerr=_yerr(top_cis), capsize=4,
               color="#4C72B0", alpha=0.9)
    ax_top.set_xticks(x)
    ax_top.set_xticklabels(top_labels, fontsize=9, rotation=12, ha="right")
    ax_top.set_ylabel("Recall@5")
    ax_top.set_ylim(0, 1.05)
    ax_top.set_title("(a) Retrieval ablation", fontsize=11)

    # Bottom: faithfulness + answer correctness across baseline systems (1-5).
    sys_labels = [d for _, d in _GENERATION_ROWS]
    faith_cis = [_vertex(scores, n, "context_faithfulness") for n, _ in _GENERATION_ROWS]
    corr_cis = [_vertex(scores, n, "answer_correctness") for n, _ in _GENERATION_ROWS]
    faith_vals = [(_mean(c) or 0.0) for c in faith_cis]
    corr_vals = [(_mean(c) or 0.0) for c in corr_cis]
    xb = np.arange(len(sys_labels))
    w = 0.38
    ax_bot.bar(xb - w / 2, faith_vals, w, yerr=_yerr(faith_cis), capsize=4,
               label="Faithfulness", color="#4C72B0", alpha=0.9)
    ax_bot.bar(xb + w / 2, corr_vals, w, yerr=_yerr(corr_cis), capsize=4,
               label="Answer correctness", color="#DD8452", alpha=0.9)
    ax_bot.set_xticks(xb)
    ax_bot.set_xticklabels(sys_labels, fontsize=9, rotation=12, ha="right")
    ax_bot.set_ylabel("Score (1--5)")
    ax_bot.set_ylim(0, 5.3)
    ax_bot.legend(fontsize=9)
    ax_bot.set_title("(b) End-to-end answer quality", fontsize=11)

    plt.tight_layout()
    for ext in ("pdf", "png"):
        path = f"{out_base}.{ext}"
        plt.savefig(path, dpi=200, bbox_inches="tight")
        print(f"  Saved {path}")
    plt.close()


# ─── Supplementary: per-category retrieval (full system) ──────────────────────

def _supp_category_retrieval(scores: Dict, out_path: str):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        return
    per_cat = (_variant(scores, "full_system").get("retrieval", {})
               .get("per_category", {}))
    if not per_cat:
        return
    cats = sorted(per_cat.keys())
    metrics = [("recall@1", "Recall@1"), ("recall@5", "Recall@5"), ("mrr", "MRR")]
    x = np.arange(len(cats))
    w = 0.25
    colors = ["#4C72B0", "#DD8452", "#55A868"]
    fig, ax = plt.subplots(figsize=(max(7, len(cats) * 2), 4.5))
    for i, (mk, ml) in enumerate(metrics):
        vals = [(per_cat.get(c, {}).get(mk, {}) or {}).get("mean") or 0.0 for c in cats]
        ax.bar(x + i * w, vals, w, label=ml, color=colors[i], alpha=0.9)
    ax.set_xticks(x + w)
    ax.set_xticklabels([c.capitalize() for c in cats])
    ax.set_ylabel("Score")
    ax.set_ylim(0, 1.1)
    ax.set_title("Retrieval by question category (full system)")
    ax.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  Saved {out_path}")


# ─── Main entry point ─────────────────────────────────────────────────────────

def export(scores: Dict) -> None:
    """Write the four paper tables + Figure 5 into generated/, plus supplements."""
    os.makedirs(GENERATED_DIR, exist_ok=True)
    os.makedirs(PAPER_DIR, exist_ok=True)

    tables = {
        "table_retrieval.tex":  _table_retrieval(scores),
        "table_generation.tex": _table_generation(scores),
        "table_ablation.tex":   _table_ablation(scores),
        "table_ops.tex":        _table_ops(scores),
    }
    for fname, content in tables.items():
        path = os.path.join(GENERATED_DIR, fname)
        with open(path, "w") as f:
            f.write(content)
        print(f"  Saved {path}")

    print("Generating Figure 5 (evaluation summary)...")
    _figure_eval(scores, os.path.join(GENERATED_DIR, "fig_eval"))

    print("Generating supplementary per-category retrieval chart...")
    _supp_category_retrieval(scores, os.path.join(PAPER_DIR, "category_retrieval.png"))

    print(f"\nPaper tables/figure written to {GENERATED_DIR}")
